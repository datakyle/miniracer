// Regenerates src/core/schedule.js: for each day, which generator attempt
// produces the day's track. Run after changing anything in track.js, sim.js
// or bot.js that affects which tracks pass (tests will fail until you do):
//
//   node scripts/gen-schedule.mjs
import { writeFileSync } from 'node:fs';
import { searchDay } from '../src/core/day.js';

const START = '2026-10-01';
const END = '2028-12-31';

const attempts = [];
for (let t = Date.parse(`${START}T00:00:00Z`); t <= Date.parse(`${END}T00:00:00Z`); t += 86400000) {
  const key = new Date(t).toISOString().slice(0, 10);
  attempts.push(searchDay(key).attempt);
}
const out = `// Generated by scripts/gen-schedule.mjs. Do not edit by hand.
// attempt index per day, starting ${START}
export const SCHEDULE_START = '${START}';
export const SCHEDULE_ATTEMPTS = [${attempts.join(',')}];
`;
writeFileSync(new URL('../src/core/schedule.js', import.meta.url), out);
console.log(`wrote ${attempts.length} days (${START} to ${END})`);
